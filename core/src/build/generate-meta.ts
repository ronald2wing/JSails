/*  Component registry                                                 */
/* ------------------------------------------------------------------ */

/**
 * Emit `.jsails/components.registry.ts`: one `registerComponent(component)`
 * call per component module, importing the conventional export name.
 */
export function emitComponentsRegistry(
  components: readonly ComponentModule[],
  rootDir: string,
): string {
  if (components.length === 0) {
    return `${HEADER}export {};\n`;
  }

  const imports = components
    .map((component) => {
      const specifier = relativeSpecifier(rootDir, component.relative);
      return `import { ${component.exportName} } from '${specifier}';`;
    })
    .join('\n');

  const calls = components
    .map((component) => `registerComponent(${component.exportName});`)
    .join('\n');

  return `${HEADER}import { registerComponent } from 'jsails/server-components';\n${imports}\n\n${calls}\n`;
}

