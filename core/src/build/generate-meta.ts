/* ------------------------------------------------------------------ */
/*  Constants                                                          */
/* ------------------------------------------------------------------ */

/** The generated-artifacts directory, at the project root. */
export const META_DIR = '.jsails';

/**
 * Absolute path of the framework package root, resolved from this compiled
 * module (`dist/src/build/generate-meta.js` → repo root). The framework-symbol
 * scan reads the framework's own barrels from here, not the app's — the app's
 * `build:meta` derives the framework table from the installed framework.
 */
const FRAMEWORK_ROOT = resolve(import.meta.dirname, '../../../');

const HEADER = '// AUTO-GENERATED by jsails build:meta. Do not edit.\n\n';

/* ------------------------------------------------------------------ */
/*  Autoload JSON                                                      */
/* ------------------------------------------------------------------ */

/**
 * Serialize the autoload registry to the JSON the Vite transform consumes.
 * Delegates the projection to {@link toAutoloadJson} so the on-disk format has
 * a single definition shared with the consumer's parser.
 */
export function emitAutoloadJson(registry: AutoloadRegistry): string {
  return JSON.stringify(toAutoloadJson(registry), null, 2) + '\n';
}

/* ------------------------------------------------------------------ */
/*  Model registry                                                     */
/* ------------------------------------------------------------------ */

/**
 * Emit `.jsails/models.registry.ts`: one `defineModel(Class, spec)` call per
 * model, importing each class from its source module. The spec is the pure data
 * {@link defineModel} lowers onto TypeORM.
 */
export function emitModelsRegistry(models: readonly ExtractedModel[], rootDir: string): string {
  if (models.length === 0) {
    return `${HEADER}export {};\n`;
  }

  // Every class the registry references: each model plus each relation target.
  // A target is imported from its own conventional module so the generated
  // `target: Author` resolves to the real class, not an undefined identifier.
  const classNames = new Set<string>();
  for (const model of models) {
    classNames.add(model.className);
    for (const field of model.fields) {
      if (field.field === 'relation') {
        classNames.add(field.target);
      }
    }
  }

  const imports = [...classNames]
    .sort(compareStrings)
    .map((className) => {
      const specifier = relativeSpecifier(rootDir, className);
      return `import { ${className} } from '${specifier}';`;
    })
    .join('\n');

  const calls = models.map((model) => emitModelCall(model)).join('\n\n');

  return `${HEADER}import { defineModel } from 'jsails/models';\n${imports}\n\n${calls}\n`;
}

/** Quote a TypeScript string literal for the generated registry. */
function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** Emit a scalar default literal. */
function emitScalar(value: string | number | boolean): string {
  return typeof value === 'string' ? quote(value) : String(value);
}

/** Emit one `defineModel(Class, { ... })` call. */
function emitModelCall(model: ExtractedModel): string {
  const columns = model.fields
    .filter((field) => field.field === 'column')
    .map((field) => {
      const parts = [`name: '${field.name}'`, `type: '${field.kind}'`];
      if (field.kind === 'varchar' && field.length !== undefined) {
        parts.push(`length: ${field.length}`);
      }
      if (field.nullable === true) {
        parts.push('nullable: true');
      }
      if (field.unique === true) {
        parts.push('unique: true');
      }
      if (field.default !== undefined) {
        parts.push(`default: ${emitScalar(field.default)}`);
      }
      if (field.temporaryDefault !== undefined) {
        parts.push(`temporaryDefault: ${emitScalar(field.temporaryDefault)}`);
      }
      if (field.renamedFrom !== undefined) {
        parts.push(`renamedFrom: ${quote(field.renamedFrom)}`);
      }
      if (field.replacedFrom !== undefined) {
        parts.push(`replacedFrom: ${quote(field.replacedFrom)}`);
      }
      if (field.copyExpression !== undefined) {
        parts.push(`copyExpression: ${quote(field.copyExpression)}`);
      }
      return `    { ${parts.join(', ')} },`;
    })
    .join('\n');

  const relations = model.fields
    .filter((field) => field.field === 'relation')
    .map((field) => {
      const parts = [`kind: '${field.kind}'`, `name: '${field.name}'`, `target: ${field.target}`];
      if (field.kind === 'one-to-one') {
        parts.push(`owning: ${field.owning}`);
      }
      if (field.joinColumn !== undefined) {
        parts.push(`joinColumn: '${field.joinColumn}'`);
      }
      if (field.onDelete !== undefined) {
        parts.push(`onDelete: '${field.onDelete}'`);
      }
      if (field.nullable === true) {
        parts.push('nullable: true');
      }
      if (field.touch === true) {
        parts.push('touch: true');
      }
      if (field.counterCache === true) {
        parts.push('counterCache: true');
      }
      if (field.inverse !== undefined) {
        parts.push(`inverse: '${field.inverse}'`);
      }
      if (field.renamedFrom !== undefined) {
        parts.push(`renamedFrom: '${field.renamedFrom}'`);
      }
      return `    { ${parts.join(', ')} },`;
    })
    .join('\n');

  const columnsBlock = columns.length > 0 ? `\n${columns}` : '';
  const relationsBlock = relations.length > 0 ? `\n${relations}` : '';
  const encryptedBlock =
    model.encrypted.length > 0
      ? `\n  encrypted: [${model.encrypted.map((field) => `'${field}'`).join(', ')}],`
      : '';

  const renamedFromBlock =
    model.renamedFrom !== undefined ? `\n  renamedFrom: ${quote(model.renamedFrom)},` : '';

  return `defineModel(${model.className}, {
  table: '${model.tableName}',${renamedFromBlock}
  primaryKey: { name: 'id', kind: 'integer' },
  columns: [${columnsBlock}
  ],
  relations: [${relationsBlock}
  ],${encryptedBlock}
});`;
}

