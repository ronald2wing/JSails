/** The web preset sections, in document order. */
function webGuidePrefix({ variant, enabled }: WebGuideInputs): string {
  const sections: GuideSection[] = [
    webIntroSection(variant),
    webProjectModulesSection(),
    webGettingStartedSection(),
    webScriptsSection(),
    webAuthenticationSection(enabled),
    webCliSignInSection(),
    webAdminAndPluginsSection(enabled),
    webTestingSection(),
    webBrowserTestsSection(),
    webLayoutSection(),
    webIslandsSection(),
    webServerComponentsSection(),
  ];
  if (variant === 'blog') sections.push(webBlogSection());
  if (variant === 'saas') sections.push(webMultiTenancySection());
  return joinSections(sections);
}

