/**
 * Starter guide text: the preset-specific sections prepended to the bundled
 * framework guide in every generated `AGENTS.md`.
 *
 * Each section is one function whose strings sit next to the facts they
 * describe, so a template change can be checked against the matching section.
 * The functions are pure text construction; `renderWebGuide`,
 * `renderCliGuide`, and `renderStaticGuide` assemble a complete guide from the
 * sections, the shared references block, and the guide body.
 */

import type { WebStarterVariant } from './presets.js';

/** The lines of one guide section, joined with newlines by the renderer. */
type GuideSection = readonly string[];

/** Inputs that vary between the server-rendered web presets. */
export interface WebGuideInputs {
  /** The web preset the guide describes. */
  readonly variant: WebStarterVariant;
  /** The `plugins.enabled` literal written into `jsails.app.js`. */
  readonly enabled: string;
}

/** Join sections into one document; a blank line separates consecutive sections. */
function joinSections(sections: readonly GuideSection[]): string {
  return sections.map((section) => section.join('\n')).join('\n\n');
}

