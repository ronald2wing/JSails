/** Assemble a complete guide: preset sections, the references, then the guide body. */
function renderGuide(prefix: string, guide: string): string {
  return `${prefix}\n\n${referencesSection().join('\n')}\n${guide}`;
}

/** The `AGENTS.md` of a server-rendered web preset. */
export function renderWebGuide(guide: string, inputs: WebGuideInputs): string {
  return renderGuide(webGuidePrefix(inputs), guide);
}

