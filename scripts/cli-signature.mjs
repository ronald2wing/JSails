/**
 * The CLI signature snapshot (`api/cli.md`): the generated help of every
 * built-in `jsails` command, in manifest order, read from the built
 * `core/dist/src/cli/manifest.js` and rendered by `help.js`. A command's
 * name, arguments, options and their summaries are the CLI's semver
 * contract, so a change to them is reviewed here line by line: `--check`
 * (the `cli-signature` gate) fails when the committed snapshot differs from
 * the built manifest, and `--write` records it after a build. A core test
 * compares each section with what the `jsails` executable prints.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { repoRoot as defaultRoot } from './workspaces.mjs';

/** The snapshot, relative to the repo root. */
export const SNAPSHOT = 'api/cli.md';

const HEADER = `<!-- Generated by scripts/cli-signature.mjs from core/dist. Do not edit; run \`node scripts/cli-signature.mjs --write\` after a build. -->

# jsails CLI signature

The help \`jsails <command> --help\` prints for every built-in command, in the
order \`jsails --help\` lists them. Names, arguments, options and their
summaries are the CLI's public contract: review a change line by line.
`;

/** Import a built core module by its path under `core/dist/src/cli`. */
function load(root, module) {
  return import(pathToFileURL(join(root, 'core', 'dist', 'src', 'cli', module)).href);
}

/** The snapshot of the built manifest under `root`. */
export async function renderSnapshot(root) {
  const { BUILTIN_COMMANDS } = await load(root, 'manifest.js');
  const { renderCommandHelp } = await load(root, 'help.js');
  const sections = BUILTIN_COMMANDS.map(
    (command) => `## ${command.name}\n\n\`\`\`text\n${renderCommandHelp(command)}\`\`\`\n`,
  );
  return `${HEADER}\n${sections.join('\n')}`;
}

/**
 * The section of `name` in a snapshot's text: the help between its fence, or
 * `undefined` when the snapshot has none.
 */
export function sectionOf(snapshot, name) {
  const start = snapshot.indexOf(`\n## ${name}\n\n\`\`\`text\n`);
  if (start === -1) return undefined;
  const body = start + `\n## ${name}\n\n\`\`\`text\n`.length;
  const end = snapshot.indexOf('```\n', body);
  return end === -1 ? undefined : snapshot.slice(body, end);
}

export async function main(argv, { root = defaultRoot } = {}) {
  const expected = await renderSnapshot(root);
  const path = join(root, SNAPSHOT);
  if (argv.includes('--write')) {
    writeFileSync(path, expected);
    return { status: 0, messages: [`cli-signature: wrote ${SNAPSHOT}`] };
  }
  let actual = '';
  try {
    actual = readFileSync(path, 'utf8');
  } catch {
    // A missing snapshot reads as empty, so the comparison below names it.
  }
  if (actual === expected) return { status: 0, messages: [] };
  return {
    status: 1,
    messages: [
      `${SNAPSHOT} does not match the help of the built commands; review the change, then run \`node scripts/cli-signature.mjs --write\``,
    ],
  };
}

if (import.meta.main) {
  const { status, messages } = await main(process.argv.slice(2));
  for (const message of messages) (status === 0 ? console.log : console.error)(message);
  process.exitCode = status;
}
