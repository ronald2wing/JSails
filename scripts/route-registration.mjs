/**
 * The first-party surface registration snapshot (`api/routes.md`): every route
 * the framework and its first-party plugins register, with each route's kind,
 * methods, pattern, access, surface kind, credentials, cross-site rule, owner
 * and origin, in the order assembly compiles them, then every surface that is
 * not a route (the public files).
 *
 * It assembles one app from the built workspaces (`core/dist`, each
 * package's `dist`) with every first-party plugin that serves HTTP, each
 * configured to register its full surface: the dev plugin, `@jsails/auth`
 * with every optional surface on, `@jsails/admin` with every first-party
 * admin plugin (blog, blog themes, media, configuration, feature flags, jobs,
 * the plugin manager), `@jsails/blog` with its create route,
 * `@jsails/mail`'s development preview, `@jsails/webhook` with one endpoint,
 * the server-component transport, introspection, and the health and
 * readiness probes. Nothing connects: every store is in memory and every
 * seam the registration never calls is a stub that throws.
 *
 * The list is the framework's public surface, so a change to it is reviewed
 * line by line: `--check` (the `route-registration` gate) fails when the
 * committed snapshot differs from what the built workspaces register, and
 * `--write` records it after a build. What the pipeline does with each
 * surface's requests is the access matrix's (`scripts/check-access.mjs`),
 * which fails when a surface of this app ({@link collectSurfaces}) is in
 * none of its apps as registered here.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { repoRoot as defaultRoot } from './workspaces.mjs';

/** The snapshot, relative to the repo root. */
export const SNAPSHOT = 'api/routes.md';

const HEADER = `<!-- Generated by scripts/route-registration.mjs from the built workspaces. Do not edit; run \`node scripts/route-registration.mjs --write\` after a build. -->

# First-party route registration

Every route the framework and its first-party plugins register, in the order
assembly compiles them, then every surface that is not a route (see
\`scripts/route-registration.mjs\` for the plugin options that open each
optional surface). A change here changes the public surface of the framework:
review it line by line.

Each route line: kind methods pattern access surface=kind credentials=list,
then the cross-site rule (cross-site=origin: core's access chain refuses an
unsafe request from another origin; cross-site=none: the route reads no
cookie), then the declared body (body=kind:bytes) and deadlines (timeout=ms,
stream-idle=ms) when a route states them, then owner/origin. A multipart
body adds its parts: parts=count field=bytes header=bytes body-idle=ms, then
each file field in name order as file:"name"=bytesxcount:types
(1024x2:image/png,image/webp), or :any when the field accepts every media
type. Each other surface line: surface id, methods, pattern, access, surface kind,
credentials, owner.

\`\`\`text
`;

/** Import a built module of the repo by its path from the root. */
function load(root, path) {
  return import(pathToFileURL(join(root, path)).href);
}

/** A seam the registration never calls: calling it is a snapshot bug. */
function unused(name) {
  return () => {
    throw new Error(`route-registration: ${name} is not called while routes register`);
  };
}

/** One route as a snapshot line. */
export function formatRoute(meta) {
  const access = accessText(meta.access);
  const credentials = meta.credentials.length === 0 ? 'none' : meta.credentials.join(',');
  return `${meta.kind} ${meta.methods.join(',')} ${meta.pattern} ${access} surface=${meta.surface} credentials=${credentials} cross-site=${crossSiteRule(meta)}${limits(meta)} ${meta.owner}/${meta.origin}`;
}

/** Who refuses a cross-site request to the route: core's access chain, or nobody (it reads no cookie). */
function crossSiteRule(meta) {
  return meta.credentials.includes('cookie') ? 'origin' : 'none';
}

/** The access of a route or surface as snapshot text: its kind, then its reason. */
function accessText(access) {
  return access.reason === '' ? access.kind : `${access.kind}(${access.reason})`;
}

/** One surface that is not a route (the public files) as a snapshot line. */
export function formatSurface(surface) {
  const credentials = surface.credentials.length === 0 ? 'none' : surface.credentials.join(',');
  return `surface ${surface.id} ${surface.match.methods.join(',')} ${surface.match.pattern} ${accessText(surface.access)} surface=${surface.kind} credentials=${credentials} ${surface.owner}`;
}

/**
 * The body and deadline a route declares, as ` body=<kind>[:<bytes>]` (and
 * a multipart body's parts) and ` timeout=<ms>`.
 */
function limits(meta) {
  let text = '';
  if (meta.body !== undefined) {
    text += ` body=${meta.body.kind}${meta.body.kind === 'none' ? '' : `:${meta.body.maxBytes}`}`;
    if (meta.body.kind === 'multipart') text += parts(meta.body.parts);
  }
  if (meta.timeoutMs !== undefined) text += ` timeout=${meta.timeoutMs}`;
  if (meta.stream !== undefined) text += ` stream-idle=${meta.stream.timeoutMs}`;
  return text;
}

/**
 * A multipart body's parts as the route table holds them (checked, every
 * default stated): its counts and bounds, then each file field in name
 * order with its cap, count and media types, so widening any of them
 * changes the line.
 */
function parts(spec) {
  let text = ` parts=${spec.maxParts} field=${spec.maxFieldBytes} header=${spec.maxHeaderBytes} body-idle=${spec.idleMs}`;
  for (const name of Object.keys(spec.files).sort()) {
    const file = spec.files[name];
    const types = file.contentTypes === undefined ? 'any' : file.contentTypes.join(',');
    text += ` file:${JSON.stringify(name)}=${file.maxBytes}x${file.maxCount}:${types}`;
  }
  return text;
}

/** What a route and its surface share: owner, methods and pattern. */
function surfaceKey(owner, methods, pattern) {
  return `${owner} ${methods.join(',')} ${pattern}`;
}

/** The snapshot document for `lines`. */
export function renderSnapshot(lines) {
  return `${HEADER}${lines.join('\n')}\n\`\`\`\n`;
}

/**
 * Assemble the first-party app from the built workspaces under `root` and
 * return its route table, then its other surfaces, as snapshot lines.
 */
export async function collectRoutes(root) {
  const { core, surfacesOf, app, close } = await assembleFirstParty(root);
  try {
    const routes = core.routeTableOf(app).entries();
    const routeKeys = new Set(
      routes.map((meta) => surfaceKey(meta.owner, meta.methods, meta.pattern)),
    );
    const others = surfacesOf(app)
      .entries()
      .filter(
        (surface) =>
          !routeKeys.has(surfaceKey(surface.owner, surface.match.methods, surface.match.pattern)),
      );
    return [...routes.map(formatRoute), ...others.map(formatSurface)];
  } finally {
    await close();
  }
}

/**
 * The surface descriptors of the first-party app assembled from the built
 * workspaces under `root`, in registration order.
 */
export async function collectSurfaces(root) {
  const { surfacesOf, app, close } = await assembleFirstParty(root);
  try {
    return surfacesOf(app).entries();
  } finally {
    await close();
  }
}

/** The first-party app assembled from the built workspaces under `root`. */
async function assembleFirstParty(root) {
  const core = await load(root, 'core/dist/src/index.js');
  const { surfacesOf } = await load(root, 'core/dist/src/security/index.js');
  const { createAssetIndex } = await load(root, 'core/dist/src/app/index.js');
  const { devPlugin } = await load(root, 'core/dist/src/dev/index.js');
  const { serverComponentsToken } = await load(
    root,
    'core/dist/src/server-components/extension.js',
  );
  const { DEFAULT_RUNTIME_LIMITS: lanes } = await load(
    root,
    'core/dist/src/server-components/runtime/admission.js',
  );
  const auth = await load(root, 'packages/auth/dist/src/index.js');
  const admin = await load(root, 'packages/admin/dist/src/index.js');
  const blog = await load(root, 'packages/blog/dist/src/index.js');
  const blogAdmin = await load(root, 'packages/blog/dist/src/admin/index.js');
  const media = await load(root, 'packages/media/dist/src/index.js');
  const mediaAdmin = await load(root, 'packages/media/dist/src/admin/index.js');
  const config = await load(root, 'packages/config/dist/src/index.js');
  const configAdmin = await load(root, 'packages/config/dist/src/admin/index.js');
  const { flagsPlugin } = await load(root, 'packages/flags/dist/src/index.js');
  const flagsAdmin = await load(root, 'packages/flags/dist/src/admin/index.js');
  const theme = await load(root, 'packages/theme/dist/src/index.js');
  const mail = await load(root, 'packages/mail/dist/src/index.js');
  const webhook = await load(root, 'packages/webhook/dist/src/index.js');
  const { MemoryDisk } = await load(root, 'packages/filesystem/dist/src/index.js');
  const { cachePlugin } = await load(root, 'packages/cache/dist/src/index.js');

  const adminOnly = (session) => session?.user?.role === 'admin';
  const repository = blog.createMemoryBlogRepository();
  const themes = theme.createThemeRegistry({ packages: theme.builtinThemePackages });
  const siteConfig = config.configPlugin({ sets: [blog.blogSiteConfig] });
  const panel = admin.defineAdminPanel({
    auth: auth.authSessionToken,
    authorize: adminOnly,
    adminPlugins: [
      blogAdmin.blogAdmin({ repository }),
      blogAdmin.blogThemeAdmin({ registry: themes, repository }),
      mediaAdmin.mediaAdmin({
        library: media.createMediaLibrary({
          disk: new MemoryDisk(),
          diskName: 'memory',
          metadata: media.createMemoryMediaIndex(),
        }),
      }),
      configAdmin.configAdmin(),
      flagsAdmin.flagsAdmin(),
      admin.jobsAdmin({
        metrics: { snapshot: unused('jobs.metrics') },
        failed: { list: unused('jobs.failed') },
      }),
    ].map((plugin) => admin.withAdminAuthorize(plugin, adminOnly)),
  });

  const runtime = await core.runExtensions(
    [
      {
        name: 'components',
        setup: ({ services }) =>
          services.provide(serverComponentsToken, {
            routes: {
              update: unused('components.update'),
              upload: unused('components.upload'),
              download: unused('components.download'),
              // The default upload cap (10 MiB) plus the multipart slack (64 KiB).
              uploadBodyBytes: 10 * 1024 * 1024 + 64 * 1024,
              // The default lanes, as a runtime built without limits carries them.
              laneTotalMs: {
                update: Math.max(lanes.update.totalMs, lanes.refresh.totalMs),
                upload: lanes.upload.totalMs,
                download: lanes.download.totalMs,
              },
            },
          }),
      },
      devPlugin({ enabled: true }),
      auth.authPlugin({
        registration: { enabled: true },
        passwordReset: { enabled: true },
        verification: { enabled: true },
        sendMail: unused('auth.sendMail'),
        apiTokens: {
          enabled: true,
          store: {
            create: unused('tokens.create'),
            list: unused('tokens.list'),
            revoke: unused('tokens.revoke'),
            resolve: unused('tokens.resolve'),
          },
        },
      }),
      cachePlugin({ store: 'memory' }),
      flagsPlugin(),
      siteConfig,
      blog.blogPlugin({
        repository,
        createRoute: { access: (context) => adminOnly(context.session) },
      }),
      admin.adminPlugin(panel),
      mail.mailPlugin({ allowMemory: true }),
      webhook.webhookPlugin({
        endpoints: [
          {
            id: 'payments',
            path: '/webhooks/payments',
            secret: 'snapshot-only-signing-secret',
            onEvent: unused('webhook.onEvent'),
          },
        ],
      }),
    ],
    // The dev plugin and the mail preview register only in development mode,
    // which the runner reads from the environment it is given.
    { rootDir: root, env: { ...process.env, NODE_ENV: 'development' } },
  );
  try {
    const app = await core.createApp({
      manifest: { entries: [], byRoute: new Map(), notFound: [] },
      services: runtime.services,
      contributions: { routes: runtime.routes, transforms: runtime.transforms },
      healthPath: '/up',
      readiness: { path: '/ready', probes: {} },
      introspect: {
        enabled: true,
        authorize: unused('introspect.authorize'),
        sections: [],
        providers: [],
      },
      // The asset index: one surface for every file, answered before the routes.
      assets: await createAssetIndex({ roots: [] }),
    });
    return { core, surfacesOf, app, close: () => runtime.close() };
  } catch (error) {
    await runtime.close();
    throw error;
  }
}

/**
 * `--check` (the default) compares the committed snapshot with the built
 * workspaces; `--write` records the snapshot. `collect` is the route source
 * (a test passes its own).
 */
export async function main(argv, { root = defaultRoot, collect = collectRoutes } = {}) {
  const write = argv.includes('--write');
  const expected = renderSnapshot(await collect(root));
  const path = join(root, SNAPSHOT);
  if (write) {
    writeFileSync(path, expected);
    return { status: 0, messages: [`route-registration: wrote ${SNAPSHOT}`] };
  }
  let actual = '';
  try {
    actual = readFileSync(path, 'utf8');
  } catch {
    // A missing snapshot reads as empty, so the comparison below names it.
  }
  const messages = [];
  if (actual !== expected) {
    messages.push(
      `${SNAPSHOT} does not match the routes the built workspaces register; review the change, then run \`node scripts/route-registration.mjs --write\``,
    );
  }
  return { status: messages.length === 0 ? 0 : 1, messages };
}

if (import.meta.main) {
  const { status, messages } = await main(process.argv.slice(2));
  for (const message of messages) (status === 0 ? console.log : console.error)(message);
  process.exitCode = status;
}
