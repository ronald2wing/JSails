/**
 * `emit(op, dialect)`: the DDL statements of one schema operation. Pure: it
 * reads nothing and runs nothing.
 *
 * Shapes per dialect:
 *
 * - A new table is one `CREATE TABLE`; its indexes follow as `CREATE INDEX`
 *   on PostgreSQL and SQLite and are part of the statement on MariaDB.
 *   Foreign keys are inline on SQLite (which cannot add one later) and are
 *   separate `add_foreign_key` operations on the servers, after every table
 *   exists, so the index a foreign key needs is already there (InnoDB adopts
 *   it instead of creating its own) and cycles need no order.
 * - A column change is one statement: PostgreSQL's `ALTER TABLE` with one
 *   action per changed property, MariaDB's `MODIFY COLUMN` with the whole
 *   declared definition.
 * - SQLite changes everything but an added column or an index by the
 *   generic table rebuild: create the declared table beside the live one,
 *   copy the shared columns, carry the `AUTOINCREMENT` high-water mark over,
 *   drop the old table, rename the new one, recreate the indexes. The push
 *   runs it with foreign keys off and checks them before it commits.
 *
 * MariaDB string defaults assume `NO_BACKSLASH_ESCAPES`, which the schema
 * session sets (see `column-default.ts`).
 */

import type { Dialect } from '../engine/contract.js';
import type { ColumnState, ForeignKeyState, IndexState, TableState } from '../model/index.js';
import { derivedName } from '../model/model-naming.js';
import { defaultLiteral, sameDefault, stringLiteral } from './column-default.js';
import { SchemaErrors } from './schema-errors.js';
import type { SchemaOperation } from './schema-operation.js';
import type { LiveColumn, LiveTable } from './schema-state.js';

/** Quote any identifier for `dialect`, doubling the quote character inside it. */
export function quoteName(dialect: Dialect, name: string): string {
  return dialect === 'mariadb'
    ? `\`${name.replaceAll('`', '``')}\``
    : `"${name.replaceAll('"', '""')}"`;
}

function nameList(dialect: Dialect, names: readonly string[]): string {
  return names.map((name) => quoteName(dialect, name)).join(', ');
}

function onDeleteClause(action: ForeignKeyState['onDelete']): string {
  return ` ON DELETE ${action.toUpperCase()}`;
}

/** One column's definition, as `CREATE TABLE`, `ADD COLUMN` and `MODIFY COLUMN` write it. */
export function columnDefinition(
  column: ColumnState,
  dialect: Dialect,
  options: { readonly inlinePrimaryKey?: boolean; readonly check?: boolean } = {},
): string {
  const name = quoteName(dialect, column.name);
  let sql = `${name} ${column.type}`;
  switch (dialect) {
    case 'postgres':
      if (column.collation !== undefined) sql += ` COLLATE ${quoteName(dialect, column.collation)}`;
      if (column.identity) sql += ' GENERATED BY DEFAULT AS IDENTITY';
      sql += column.nullable ? ' NULL' : ' NOT NULL';
      if (column.default !== undefined)
        sql += ` DEFAULT ${defaultLiteral(column.default, dialect)}`;
      return sql;
    case 'mariadb':
      if (column.collation !== undefined) {
        sql += ` CHARACTER SET utf8mb4 COLLATE ${column.collation}`;
      }
      sql += column.nullable ? ' NULL' : ' NOT NULL';
      if (column.default !== undefined)
        sql += ` DEFAULT ${defaultLiteral(column.default, dialect)}`;
      if (column.identity) sql += ' AUTO_INCREMENT';
      if (column.check === 'json' && options.check !== false) sql += ` CHECK (json_valid(${name}))`;
      return sql;
    case 'sqlite':
      if (options.inlinePrimaryKey === true) {
        sql += ' PRIMARY KEY';
        if (column.identity) sql += ' AUTOINCREMENT';
      }
      if (!column.nullable) sql += ' NOT NULL';
      if (column.default !== undefined)
        sql += ` DEFAULT ${defaultLiteral(column.default, dialect)}`;
      return sql;
  }
}

/** Whether SQLite writes the key on its column: an `INTEGER PRIMARY KEY AUTOINCREMENT`. */
function sqliteInlineKey(table: TableState): string | undefined {
  if (table.primaryKey.length !== 1) return undefined;
  const key = table.primaryKey[0];
  return table.columns.some((column) => column.name === key && column.identity) ? key : undefined;
}

function foreignKeyClause(dialect: Dialect, foreignKey: ForeignKeyState): string {
  return (
    `CONSTRAINT ${quoteName(dialect, foreignKey.name)} FOREIGN KEY (${nameList(dialect, foreignKey.columns)}) ` +
    `REFERENCES ${quoteName(dialect, foreignKey.referencedTable)} (${nameList(dialect, foreignKey.referencedColumns)})` +
    onDeleteClause(foreignKey.onDelete)
  );
}

function createIndexStatement(
  dialect: Dialect,
  table: string,
  index: IndexState,
  options: { readonly online?: boolean; readonly ifNotExists?: boolean } = {},
): string {
  const unique = index.unique ? 'UNIQUE ' : '';
  const online = options.online === true && dialect === 'postgres' ? 'CONCURRENTLY ' : '';
  const exists = options.ifNotExists === true ? 'IF NOT EXISTS ' : '';
  const sql =
    `CREATE ${unique}INDEX ${online}${exists}${quoteName(dialect, index.name)} ` +
    `ON ${quoteName(dialect, table)} (${nameList(dialect, index.columns)})`;
  return options.online === true && dialect === 'mariadb'
    ? `${sql} ALGORITHM=INPLACE LOCK=NONE`
    : sql;
}

/** Options of {@link createTableStatements}. */
export interface CreateTableOptions {
  /** `IF NOT EXISTS` on the table and its indexes: the idempotent ledger bootstrap. */
  readonly ifNotExists?: boolean;
  /** The name to create the table under (a rebuild's temporary name). */
  readonly name?: string;
}

/** The statements that create `table` with its indexes (and SQLite foreign keys). */
export function createTableStatements(
  table: TableState,
  dialect: Dialect,
  options: CreateTableOptions = {},
): string[] {
  const name = options.name ?? table.name;
  const exists = options.ifNotExists === true ? 'IF NOT EXISTS ' : '';
  const inlineKey = dialect === 'sqlite' ? sqliteInlineKey(table) : undefined;
  const parts = table.columns.map((column) =>
    columnDefinition(column, dialect, { inlinePrimaryKey: column.name === inlineKey }),
  );
  if (inlineKey === undefined && table.primaryKey.length > 0) {
    parts.push(`PRIMARY KEY (${nameList(dialect, table.primaryKey)})`);
  }
  if (dialect === 'mariadb') {
    for (const index of table.indexes) {
      parts.push(
        `${index.unique ? 'UNIQUE KEY' : 'KEY'} ${quoteName(dialect, index.name)} (${nameList(dialect, index.columns)})`,
      );
    }
  }
  if (dialect === 'sqlite') {
    for (const foreignKey of table.foreignKeys) parts.push(foreignKeyClause(dialect, foreignKey));
  }
  const suffix = dialect === 'mariadb' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : '';
  const statements = [
    `CREATE TABLE ${exists}${quoteName(dialect, name)} (${parts.join(', ')})${suffix}`,
  ];
  if (dialect !== 'mariadb') {
    for (const index of table.indexes) {
      statements.push(
        createIndexStatement(dialect, name, index, { ifNotExists: options.ifNotExists === true }),
      );
    }
  }
  return statements;
}

function alterPostgresColumn(table: string, column: ColumnState, from: LiveColumn): string[] {
  const dialect = 'postgres';
  const name = quoteName(dialect, column.name);
  const actions: string[] = [];
  const after: string[] = [];
  const retype =
    from.type !== column.type ||
    (column.collation !== undefined && from.collation !== column.collation);
  if (from.identity && !column.identity) actions.push(`ALTER COLUMN ${name} DROP IDENTITY`);
  if (retype) {
    const collate =
      column.collation === undefined ? '' : ` COLLATE ${quoteName(dialect, column.collation)}`;
    actions.push(
      `ALTER COLUMN ${name} TYPE ${column.type}${collate} USING ${name}::${column.type}`,
    );
  }
  if (from.nullable !== column.nullable) {
    actions.push(`ALTER COLUMN ${name} ${column.nullable ? 'DROP' : 'SET'} NOT NULL`);
  }
  if (!column.identity && !sameDefault(column.default, from.default, column.portable, dialect)) {
    actions.push(
      column.default === undefined
        ? `ALTER COLUMN ${name} DROP DEFAULT`
        : `ALTER COLUMN ${name} SET DEFAULT ${defaultLiteral(column.default, dialect)}`,
    );
  }
  if (column.identity && !from.identity) {
    if (from.default !== undefined) actions.push(`ALTER COLUMN ${name} DROP DEFAULT`);
    actions.push(`ALTER COLUMN ${name} ADD GENERATED BY DEFAULT AS IDENTITY`);
    // The new sequence starts at 1; move it past the keys the table holds.
    after.push(
      `SELECT setval(pg_get_serial_sequence(${stringLiteral(quoteName(dialect, table))}, ` +
        `${stringLiteral(column.name)}), COALESCE(MAX(${name}), 0) + 1, false) ` +
        `FROM ${quoteName(dialect, table)}`,
    );
  }
  if (actions.length === 0) return [];
  return [`ALTER TABLE ${quoteName(dialect, table)} ${actions.join(', ')}`, ...after];
}

function alterMariadbColumn(table: string, column: ColumnState, from: LiveColumn): string[] {
  const dialect = 'mariadb';
  const statements: string[] = [];
  const quotedTable = quoteName(dialect, table);
  // A column check is a constraint named after the column: drop a stale one,
  // and add the declared one with the definition only when it is missing.
  if (from.check === 'json' && column.check !== 'json') {
    statements.push(
      `ALTER TABLE ${quotedTable} DROP CONSTRAINT ${quoteName(dialect, column.name)}`,
    );
  }
  statements.push(
    `ALTER TABLE ${quotedTable} MODIFY COLUMN ${columnDefinition(column, dialect, {
      check: from.check !== 'json',
    })}`,
  );
  return statements;
}

function rebuildStatements(table: TableState, from: LiveTable): string[] {
  const dialect = 'sqlite';
  const temporary = derivedName('jsails_rebuild', table.name);
  const quoted = quoteName(dialect, table.name);
  const quotedTemporary = quoteName(dialect, temporary);
  const live = new Set(from.columns.map((column) => column.name));
  const shared = table.columns
    .filter((column) => live.has(column.name))
    .map((column) => column.name);
  const statements = [
    `DROP TABLE IF EXISTS ${quotedTemporary}`,
    ...createTableStatements({ ...table, indexes: [] }, dialect, { name: temporary }),
  ];
  if (shared.length > 0) {
    statements.push(
      `INSERT INTO ${quotedTemporary} (${nameList(dialect, shared)}) ` +
        `SELECT ${nameList(dialect, shared)} FROM ${quoted}`,
    );
  }
  if (table.columns.some((column) => column.identity)) {
    // Keep the AUTOINCREMENT high-water mark, so a deleted key is never reused.
    const oldName = stringLiteral(table.name);
    const newName = stringLiteral(temporary);
    statements.push(
      `UPDATE sqlite_sequence SET seq = (SELECT MAX(seq) FROM sqlite_sequence WHERE name IN (${oldName}, ${newName})) WHERE name = ${newName}`,
      `INSERT INTO sqlite_sequence (name, seq) SELECT ${newName}, seq FROM sqlite_sequence ` +
        `WHERE name = ${oldName} AND NOT EXISTS (SELECT 1 FROM sqlite_sequence WHERE name = ${newName})`,
    );
  }
  statements.push(
    `DROP TABLE ${quoted}`,
    `ALTER TABLE ${quotedTemporary} RENAME TO ${quoted}`,
    ...table.indexes.map((index) => createIndexStatement(dialect, table.name, index)),
  );
  return statements;
}

/** The statements of `op` on `dialect`; empty for a ledger-only operation. */
export function emit(op: SchemaOperation, dialect: Dialect): string[] {
  const unsupported = (): never => {
    throw new SchemaErrors.Error('unsupported_operation', { operation: op.kind, dialect });
  };
  switch (op.kind) {
    case 'create_table':
      return createTableStatements(op.table, dialect);
    case 'drop_table':
      return [`DROP TABLE ${quoteName(dialect, op.table)}`];
    case 'adopt_table':
    case 'forget_table':
      return [];
    case 'add_column':
      return [
        `ALTER TABLE ${quoteName(dialect, op.table)} ADD COLUMN ${columnDefinition(op.column, dialect)}`,
      ];
    case 'drop_column':
      return [
        `ALTER TABLE ${quoteName(dialect, op.table)} DROP COLUMN ${quoteName(dialect, op.column)}`,
      ];
    case 'alter_column':
      if (dialect === 'postgres') return alterPostgresColumn(op.table, op.column, op.from);
      if (dialect === 'mariadb') return alterMariadbColumn(op.table, op.column, op.from);
      return unsupported();
    case 'create_index':
      return [createIndexStatement(dialect, op.table, op.index, { online: op.online })];
    case 'drop_index':
      if (dialect === 'postgres' && op.index.constraint) {
        return [
          `ALTER TABLE ${quoteName(dialect, op.table)} DROP CONSTRAINT ${quoteName(dialect, op.index.name)}`,
        ];
      }
      return dialect === 'mariadb'
        ? [`DROP INDEX ${quoteName(dialect, op.index.name)} ON ${quoteName(dialect, op.table)}`]
        : [`DROP INDEX ${quoteName(dialect, op.index.name)}`];
    case 'add_foreign_key':
      if (dialect === 'sqlite') return unsupported();
      return [
        `ALTER TABLE ${quoteName(dialect, op.table)} ADD ${foreignKeyClause(dialect, op.foreignKey)}`,
      ];
    case 'drop_foreign_key':
      if (dialect === 'sqlite') return unsupported();
      return [
        `ALTER TABLE ${quoteName(dialect, op.table)} DROP ${dialect === 'mariadb' ? 'FOREIGN KEY' : 'CONSTRAINT'} ${quoteName(dialect, op.foreignKey)}`,
      ];
    case 'set_primary_key': {
      if (dialect === 'sqlite') return unsupported();
      const actions: string[] = [];
      if (op.hadKey) {
        actions.push(
          dialect === 'mariadb'
            ? 'DROP PRIMARY KEY'
            : `DROP CONSTRAINT ${quoteName(dialect, op.from ?? `${op.table}_pkey`)}`,
        );
      }
      if (op.columns.length > 0) actions.push(`ADD PRIMARY KEY (${nameList(dialect, op.columns)})`);
      return actions.length === 0
        ? []
        : [`ALTER TABLE ${quoteName(dialect, op.table)} ${actions.join(', ')}`];
    }
    case 'rebuild_table':
      if (dialect !== 'sqlite') return unsupported();
      return rebuildStatements(op.table, op.from);
  }
}
