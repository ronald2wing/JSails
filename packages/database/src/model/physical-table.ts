/**
 * `physicalTable(model, dialect)`: the single lowering of a model to a
 * dialect's table. Pure: no connection, no driver, no TypeORM. Its result
 * feeds both the schema diff (DAT-06 introspects a database into the same
 * {@link TableState} shape and compares) and the runtime mapper (each column
 * carries its property, portable type and encryption).
 *
 * Column types are spelled as the server reports them (`format_type` on
 * PostgreSQL, `COLUMN_TYPE` on MariaDB, the declared type on SQLite), in
 * lowercase, and are valid DDL as written. Text columns carry their collation
 * explicitly: `"C"` on PostgreSQL and `utf8mb4_nopad_bin` on MariaDB, so
 * equality and order are by code point on every dialect, case and trailing
 * spaces included.
 *
 * Indexes: the declared ones, then an automatic index on every owning
 * foreign key, every polymorphic `(type, id)` pair and the tenant column,
 * unless the primary key or an index already leads with the same columns.
 * A relation opts out with `index: false`. The same explicit index is
 * declared on every dialect, so MariaDB's implicit foreign-key index is
 * never relied on.
 */

import type { Dialect, SqlValue } from '../engine/contract.js';
import { modelDefinition, modelSpec } from './define-model.js';
import { ModelSpecError } from './model-error.js';
import { foreignKeyName, indexName } from './model-naming.js';
import type {
  BelongsToSpec,
  EncryptionSpec,
  ModelTarget,
  NormalizedSpec,
  OnDelete,
  RelationSpec,
  ResolvedColumn,
} from './model-spec.js';
import { portableCodec, SQLITE_SCALED_DECIMAL_PRECISION } from './portable-codec.js';
import { sameType, type PortableType } from './portable-type.js';
import { storedType } from './spec-validation.js';

/** A column default as the table declares it. */
export type ColumnDefaultState =
  | { readonly kind: 'value'; readonly value: SqlValue }
  /** The current instant, in the column's timestamp encoding. */
  | { readonly kind: 'now' };

/** One column of a {@link TableState}. */
export interface ColumnState {
  readonly name: string;
  /** The model property the column holds. */
  readonly property: string;
  /** The portable type of the application value (before encryption). */
  readonly portable: PortableType;
  readonly encrypted?: EncryptionSpec;
  /** The dialect's column type, lowercase, as the server reports it. */
  readonly type: string;
  readonly nullable: boolean;
  readonly collation?: string;
  /**
   * Generated by the database as an identity that never reuses a value
   * (`GENERATED BY DEFAULT AS IDENTITY`, `AUTO_INCREMENT`, SQLite's
   * `INTEGER PRIMARY KEY AUTOINCREMENT`).
   */
  readonly identity: boolean;
  readonly default?: ColumnDefaultState;
  /** A check the column carries: MariaDB's `json_valid` for `json`. */
  readonly check?: 'json';
}

/** Why an index exists. */
export type IndexOrigin = 'declared' | 'foreign-key' | 'polymorphic' | 'tenant';

export interface IndexState {
  readonly name: string;
  readonly columns: readonly string[];
  readonly unique: boolean;
  readonly origin: IndexOrigin;
}

export interface ForeignKeyState {
  readonly name: string;
  readonly columns: readonly string[];
  readonly referencedTable: string;
  readonly referencedColumns: readonly string[];
  readonly onDelete: OnDelete;
  /** Whether the relation opted out of its automatic index (`index: false`). */
  readonly indexed: boolean;
}

/** A table as one dialect declares it. */
export interface TableState {
  readonly name: string;
  readonly columns: readonly ColumnState[];
  /** Physical primary-key columns, in key order. */
  readonly primaryKey: readonly string[];
  readonly indexes: readonly IndexState[];
  readonly foreignKeys: readonly ForeignKeyState[];
  /** The physical tenant column of a tenant-scoped table. */
  readonly tenant?: string;
}

interface PhysicalType {
  readonly type: string;
  readonly collation?: string;
  readonly check?: 'json';
}

function postgresType(type: PortableType): PhysicalType {
  switch (type.kind) {
    case 'id':
    case 'bigint':
      return { type: 'bigint' };
    case 'string':
      return { type: `character varying(${type.length})`, collation: 'C' };
    case 'text':
      return { type: 'text', collation: 'C' };
    case 'integer':
      return { type: 'integer' };
    case 'decimal':
      return { type: `numeric(${type.precision},${type.scale})` };
    case 'float':
      return { type: 'double precision' };
    case 'boolean':
      return { type: 'boolean' };
    case 'timestamp':
      return { type: 'timestamp(3) with time zone' };
    case 'date':
      return { type: 'date' };
    case 'time':
      return { type: 'time(3) without time zone' };
    case 'json':
      return { type: 'jsonb' };
    case 'uuid':
      return { type: 'uuid' };
    case 'binary':
      return { type: 'bytea' };
  }
}

function mariadbType(type: PortableType): PhysicalType {
  switch (type.kind) {
    case 'id':
    case 'bigint':
      return { type: 'bigint' };
    case 'string':
      return { type: `varchar(${type.length})`, collation: 'utf8mb4_nopad_bin' };
    case 'text':
      return { type: 'longtext', collation: 'utf8mb4_nopad_bin' };
    case 'integer':
      return { type: 'int' };
    case 'decimal':
      return { type: `decimal(${type.precision},${type.scale})` };
    case 'float':
      return { type: 'double' };
    case 'boolean':
      return { type: 'tinyint(1)' };
    case 'timestamp':
      return { type: 'datetime(3)' };
    case 'date':
      return { type: 'date' };
    case 'time':
      return { type: 'time(3)' };
    case 'json':
      // MariaDB's JSON is this type with this check; spelled out, it
      // introspects as written.
      return { type: 'longtext', collation: 'utf8mb4_bin', check: 'json' };
    case 'uuid':
      return { type: 'binary(16)' };
    case 'binary':
      return { type: type.length === undefined ? 'longblob' : `varbinary(${type.length})` };
  }
}

function sqliteType(type: PortableType): PhysicalType {
  switch (type.kind) {
    case 'id':
    case 'integer':
    case 'bigint':
    case 'boolean':
      return { type: 'integer' };
    case 'decimal':
      return { type: type.precision <= SQLITE_SCALED_DECIMAL_PRECISION ? 'integer' : 'text' };
    case 'float':
      return { type: 'real' };
    case 'binary':
      return { type: 'blob' };
    case 'string':
    case 'text':
    case 'timestamp':
    case 'date':
    case 'time':
    case 'json':
    case 'uuid':
      return { type: 'text' };
  }
}

/** The dialect column type of a stored portable type. */
export function physicalType(type: PortableType, dialect: Dialect): PhysicalType {
  switch (dialect) {
    case 'postgres':
      return postgresType(type);
    case 'mariadb':
      return mariadbType(type);
    case 'sqlite':
      return sqliteType(type);
  }
}

function sameModel(a: ModelTarget, b: ModelTarget): boolean {
  const left = modelDefinition(a);
  return left !== undefined && left === modelDefinition(b);
}

function resolveTarget(
  spec: NormalizedSpec,
  name: string,
  thunk: () => ModelTarget,
): NormalizedSpec {
  let target: unknown;
  try {
    target = thunk();
  } catch {
    // A thunk that throws (a model module still loading) is an unresolved
    // target; its own error says nothing the caller can act on here.
    target = undefined;
  }
  const definition = modelDefinition(target);
  if (definition === undefined) {
    throw new ModelSpecError('unresolved_relation', {
      model: spec.name,
      field: `relations.${name}`,
    });
  }
  return definition.spec;
}

function columnOf(spec: NormalizedSpec, property: string): ResolvedColumn | undefined {
  return spec.columns.find((column) => column.property === property);
}

function physicalOf(spec: NormalizedSpec, property: string): string {
  const column = columnOf(spec, property);
  if (column === undefined)
    throw new ModelSpecError('unknown_column', { model: spec.name, field: property });
  return column.column;
}

function relationOf(spec: NormalizedSpec, name: string): RelationSpec | undefined {
  return Object.hasOwn(spec.relations, name) ? spec.relations[name] : undefined;
}

/**
 * The FK action a `belongsTo` lowers to: the one its inverse's `dependent`
 * implies, else its own `onDelete`, else `restrict`. An `onDelete` that
 * disagrees with the inverse's `dependent` is refused, since the write
 * pipeline relies on the action whenever a child's effect plan is empty.
 */
function foreignKeyAction(
  self: ModelTarget,
  spec: NormalizedSpec,
  name: string,
  relation: BelongsToSpec,
  targetSpec: NormalizedSpec,
  nullable: boolean,
): OnDelete {
  const fail = (): never => {
    throw new ModelSpecError('invalid_relation', { model: spec.name, field: `relations.${name}` });
  };
  const actions = new Set<OnDelete>();
  for (const inverse of Object.values(targetSpec.relations)) {
    if (inverse.kind === 'belongsTo' || !('inverse' in inverse) || inverse.inverse !== name) {
      continue;
    }
    if (inverse.dependent === undefined) continue;
    let inverseTarget: unknown;
    try {
      inverseTarget = inverse.target();
    } catch {
      // An unloadable inverse target is reported when the target's own table is lowered.
      continue;
    }
    if (inverseTarget === undefined || !sameModel(inverseTarget as ModelTarget, self)) continue;
    if (inverse.dependent === 'destroy') actions.add('cascade');
    else actions.add(nullable ? 'set null' : fail());
  }
  if (actions.size > 1) fail();
  const implied = actions.values().next().value;
  if (implied === undefined) return relation.onDelete ?? 'restrict';
  if (relation.onDelete !== undefined && relation.onDelete !== implied) fail();
  return implied;
}

function leads(columns: readonly string[], prefix: readonly string[]): boolean {
  return prefix.every((column, index) => columns[index] === column);
}

function columnState(column: ResolvedColumn, dialect: Dialect, generated: boolean): ColumnState {
  const stored = storedType(column);
  const physical = physicalType(stored, dialect);
  const state: { -readonly [K in keyof ColumnState]: ColumnState[K] } = {
    name: column.column,
    property: column.property,
    portable: column.type,
    type: physical.type,
    nullable: column.nullable,
    identity: generated,
  };
  if (column.encrypted !== undefined) state.encrypted = column.encrypted;
  if (physical.collation !== undefined) state.collation = physical.collation;
  if (physical.check !== undefined) state.check = physical.check;
  if (column.default !== undefined) {
    const value = column.default;
    state.default =
      typeof value === 'object'
        ? { kind: 'now' }
        : {
            kind: 'value',
            value: portableCodec(column.type, dialect).encode(
              column.type.kind === 'bigint' ? BigInt(value) : value,
            ),
          };
  }
  return Object.freeze(state);
}

/**
 * Lower a model or table to `dialect`. Throws {@link ModelSpecError} when a
 * relation's target is not a defined model, a foreign key's type differs
 * from the target's primary key, an inverse relation does not point back,
 * or two automatic and declared indexes collide by name.
 */
export function physicalTable(model: ModelTarget, dialect: Dialect): TableState {
  const spec = modelSpec(model);
  const invalid = (field: string): never => {
    throw new ModelSpecError('invalid_relation', { model: spec.name, field });
  };
  const columns = spec.columns.map((column) =>
    columnState(column, dialect, spec.generatedKey && column.property === spec.primaryKey[0]),
  );
  const primaryKey = spec.primaryKey.map((property) => physicalOf(spec, property));
  const indexes: IndexState[] = spec.indexes.map((index) =>
    Object.freeze({
      name: index.name,
      columns: Object.freeze(index.columns.map((property) => physicalOf(spec, property))),
      unique: index.unique,
      origin: 'declared' as const,
    }),
  );
  const foreignKeys: ForeignKeyState[] = [];
  const automatic: { columns: string[]; origin: IndexOrigin }[] = [];

  for (const [name, relation] of Object.entries(spec.relations)) {
    const field = `relations.${name}`;
    if (relation.kind === 'belongsTo') {
      if ('polymorphic' in relation) {
        if (relation.index !== false) {
          automatic.push({
            columns: [physicalOf(spec, `${name}Type`), physicalOf(spec, `${name}Id`)],
            origin: 'polymorphic',
          });
        }
        continue;
      }
      const targetSpec = resolveTarget(spec, name, relation.target);
      if (targetSpec.primaryKey.length !== 1) invalid(field);
      const referenced = columnOf(targetSpec, targetSpec.primaryKey[0] ?? '');
      const own = columnOf(spec, relation.foreignKey ?? `${name}Id`);
      if (referenced === undefined || own === undefined) return invalid(field);
      if (!sameType(own.type, referenced.type)) invalid(`${field}.foreignKey`);
      if (relation.counterCache !== undefined) {
        const counter = columnOf(targetSpec, relation.counterCache);
        if (counter?.type.kind !== 'integer' || counter.nullable) invalid(`${field}.counterCache`);
      }
      if (relation.touch !== undefined) {
        const touched = columnOf(targetSpec, relation.touch);
        if (touched?.type.kind !== 'timestamp') invalid(`${field}.touch`);
      }
      foreignKeys.push(
        Object.freeze({
          name: foreignKeyName(spec.table, [own.column]),
          columns: Object.freeze([own.column]),
          referencedTable: targetSpec.table,
          referencedColumns: Object.freeze([referenced.column]),
          onDelete: foreignKeyAction(model, spec, name, relation, targetSpec, own.nullable),
          indexed: relation.index !== false,
        }),
      );
      if (relation.index !== false)
        automatic.push({ columns: [own.column], origin: 'foreign-key' });
      continue;
    }
    const targetSpec = resolveTarget(spec, name, relation.target);
    if ('through' in relation) {
      const via = relationOf(spec, relation.through);
      if (via === undefined || !('target' in via)) return invalid(`${field}.through`);
      const viaSpec = resolveTarget(spec, relation.through, via.target);
      const source = relationOf(viaSpec, relation.source);
      if (source === undefined || !('target' in source)) return invalid(`${field}.source`);
      if (resolveTarget(viaSpec, relation.source, source.target) !== targetSpec) {
        invalid(`${field}.source`);
      }
      continue;
    }
    const inverse = relationOf(targetSpec, relation.inverse);
    if (inverse?.kind !== 'belongsTo') return invalid(`${field}.inverse`);
    if ('polymorphic' in inverse) {
      if (relation.dependent === 'nullify' && inverse.nullable !== true) {
        invalid(`${field}.dependent`);
      }
      continue;
    }
    const back = resolveTarget(targetSpec, relation.inverse, inverse.target);
    if (back !== spec) invalid(`${field}.inverse`);
    if (relation.dependent === 'nullify') {
      const key = columnOf(targetSpec, inverse.foreignKey ?? `${relation.inverse}Id`);
      if (key?.nullable !== true) invalid(`${field}.dependent`);
    }
  }
  if (spec.tenant !== undefined) {
    automatic.unshift({ columns: [physicalOf(spec, spec.tenant)], origin: 'tenant' });
  }

  for (const candidate of automatic) {
    const covered =
      leads(primaryKey, candidate.columns) ||
      indexes.some((index) => leads(index.columns, candidate.columns));
    if (covered) continue;
    const name = indexName(spec.table, candidate.columns, false);
    if (indexes.some((index) => index.name === name)) {
      throw new ModelSpecError('duplicate_index', { model: spec.name, field: name });
    }
    indexes.push(
      Object.freeze({
        name,
        columns: Object.freeze(candidate.columns),
        unique: false,
        origin: candidate.origin,
      }),
    );
  }

  const state: { -readonly [K in keyof TableState]: TableState[K] } = {
    name: spec.table,
    columns: Object.freeze(columns),
    primaryKey: Object.freeze(primaryKey),
    indexes: Object.freeze(indexes),
    foreignKeys: Object.freeze(foreignKeys),
  };
  if (spec.tenant !== undefined) state.tenant = physicalOf(spec, spec.tenant);
  return Object.freeze(state);
}

/**
 * The foreign-key and tenant columns of `table` that lead neither its primary
 * key nor any index: each is a full scan on every parent delete or tenant
 * query. Empty for a table `physicalTable` lowered without an `index: false`
 * opt-out.
 */
export function unindexedColumns(table: TableState): readonly string[] {
  const keys = [table.primaryKey, ...table.indexes.map((index) => index.columns)];
  const wanted = [
    ...table.foreignKeys.map((foreignKey) => foreignKey.columns),
    ...(table.tenant === undefined ? [] : [[table.tenant]]),
  ];
  return wanted
    .filter((columns) => !keys.some((key) => leads(key, columns)))
    .map((columns) => columns.join(','));
}
