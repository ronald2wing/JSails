/**
 * The `@jsails/ai` package: a provider-neutral AI runtime for JSails.
 *
 * This entry is browser-safe (no `node:*`, no provider SDK, no server-only
 * `jsails` module): the neutral content model and its validation, the
 * untrusted-input parser, the conversation codec, usage and cost accounting,
 * tools, per-provider schema lowering, `generateObject`, the provider
 * contract, the run loop (`run`, `generate`, `countTokens`), the ai.v1
 * server-sent event stream (`toEventStream`, `toEventStreamResponse`), and
 * the value-free `AiError`. The browser reads that stream through
 * `@jsails/ai/client`.
 *
 * ```ts
 * import { defineTool, generateObject, parseUserInput } from '@jsails/ai';
 * import { z } from 'zod';
 *
 * const lookupOrder = defineTool({
 *   name: 'lookup_order',
 *   description: 'Look up one of the current user’s orders by id.',
 *   input: z.object({ orderId: z.string() }),
 *   authorize: (input, ctx) => ctx.actor.kind === 'user',
 *   execute: async ({ orderId }, ctx) => orders.find(ctx.actor, orderId, ctx.signal),
 * });
 *
 * const result = await generate({
 *   model,
 *   history: conversation.messages,
 *   input: parseUserInput(body.input),
 *   tools: [lookupOrder],
 *   context: { actor },
 * });
 * ```
 */

